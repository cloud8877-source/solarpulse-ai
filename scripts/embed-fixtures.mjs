// Embeds src/data/fixtures/*.csv into src/data/fixtures.gen.ts as a string map.
// Run: npm run embed:fixtures (after editing any CSV fixtures).

import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const fixturesDir = join(root, "src", "data", "fixtures");
const outFile = join(root, "src", "data", "fixtures.gen.ts");

const csvFiles = readdirSync(fixturesDir)
  .filter((name) => name.endsWith(".csv"))
  .sort();

const entries = csvFiles.map((name) => {
  const content = readFileSync(join(fixturesDir, name), "utf8");
  return `  ${JSON.stringify(name)}: ${JSON.stringify(content)},`;
});

const source = [
  "// AUTO-GENERATED by scripts/embed-fixtures.mjs — do not edit; run npm run embed:fixtures after editing CSVs",
  "",
  "export const FIXTURE_CSV: Record<string, string> = {",
  ...entries,
  "};",
  "",
].join("\n");

writeFileSync(outFile, source, "utf8");
console.log(`Wrote ${outFile} (${csvFiles.length} fixtures)`);
